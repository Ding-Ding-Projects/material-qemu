// Checks NUMA nodes and CPU flags end to end in headless Microsoft Edge: the
// create form sets two NUMA nodes and turns a CPU flag off, the server's launch
// preview shows the QEMU arguments, the machine starts in real QEMU, and the
// Monitor tab shows two memory backends and CPUs on two NUMA nodes.
// Usage: node scripts/verify-cpu-numa.mjs <origin> <password> <out-dir>
import { spawn } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import os from "node:os";
import { createRequire } from "node:module";
import { stopBrowser, ensurePortFree } from "./browser-process.mjs";
const require = createRequire(import.meta.url);
const WebSocket = require("ws");
const [origin, password, outDir] = process.argv.slice(2);
mkdirSync(outDir, { recursive: true });
const port = 9363;
await ensurePortFree(port);
const edge = spawn("C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", ["--headless=new", `--remote-debugging-port=${port}`, `--user-data-dir=${path.join(os.tmpdir(), "mq-cn-" + Date.now())}`, "--no-first-run", "--hide-scrollbars", "about:blank"], { stdio: "ignore" });
process.on("exit", () => stopBrowser(edge));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let target;
for (let i = 0; i < 40 && !target; i++) { await sleep(250); try { target = (await (await fetch(`http://127.0.0.1:${port}/json`)).json()).find((t) => t.type === "page"); } catch {} }
const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise((r) => ws.once("open", r));
let seq = 0; const pending = new Map();
ws.on("message", (m) => { const d = JSON.parse(m); if (d.id && pending.has(d.id)) { pending.get(d.id)(d); pending.delete(d.id); } });
const send = (method, params = {}) => new Promise((r) => { const id = ++seq; pending.set(id, r); ws.send(JSON.stringify({ id, method, params })); });
const ev = async (body) => { const r = await send("Runtime.evaluate", { expression: `(async()=>{${body}})()`, awaitPromise: true, returnByValue: true }); return r.result?.exceptionDetails ? "EXC " + (r.result.exceptionDetails.exception?.description || "").slice(0, 300) : r.result?.result?.value; };
const results = [];
const machineName = `numa-check-${Date.now() % 1000000}`;
const check = (name, ok, detail = "") => { results.push({ name, ok: !!ok, detail }); console.log(ok ? "PASS" : "FAIL", name, detail); };
const shot = async (name) => { const r = await send("Page.captureScreenshot", { format: "png" }); writeFileSync(path.join(outDir, `${name}.png`), Buffer.from(r.result.data, "base64")); };
const waitFor = (js, ms = 8000) => ev(`for (let i = 0; i < ${ms / 100}; i++) { if (${js}) return true; await new Promise((r) => setTimeout(r, 100)); } return false;`);
const click = (sel) => ev(`const e=document.querySelector(${JSON.stringify(sel)}); if(!e) return 'missing'; e.click(); return 1;`);
const setField = (sel, value) => ev(`const e=document.querySelector(${JSON.stringify(sel)}); if(!e) return 'missing'; e.value=${JSON.stringify(value)}; e.dispatchEvent(new Event('input',{bubbles:true})); e.dispatchEvent(new Event('change',{bubbles:true})); return 1;`);
await send("Page.enable"); await send("Runtime.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1100, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: origin }); await sleep(2500);
await ev(`let s=await (await fetch('/api/session')).json();
const post=(u,b)=>fetch(u,{method:'POST',headers:{'content-type':'application/json','x-csrf-token':s.csrf||''},body:JSON.stringify(b)});
if(s.setupRequired) await post('/api/setup',{name:'owner',username:'owner',password:${JSON.stringify(password)}});
else if(!s.authenticated) await post('/api/login',{username:'owner',password:${JSON.stringify(password)}});
s=await (await fetch('/api/session')).json();
await post('/api/preferences',{setup:{step:8,complete:true},settings:{language:'en'}}); return 1;`);
const host = await ev(`return (await (await fetch('/api/host')).json()).cpuFlags?.length || 0`);
check("The server reports the CPU flags this QEMU build recognizes", host > 50, String(host));
await send("Page.navigate", { url: origin }); await sleep(2500);
await click('[data-action="new"]');
await waitFor(`document.querySelector('#f-name')`);
await setField("#f-name", machineName);
await click('[data-action="cfg-section:cpu"]');
await waitFor(`document.querySelector('#f-numaNodes')`);
await setField("#f-cores", "4"); await sleep(400);
await setField("#f-memory", "1024"); await sleep(400);
await setField("#f-numaNodes", "2"); await sleep(400);
await click('[data-action="cfg-add-flag"]');
await waitFor(`document.querySelector('[id="f-cpuFlags.0.name"]')`);
await setField('[id="f-cpuFlags.0.name"]', "avx2"); await sleep(200);
await setField('[id="f-cpuFlags.0.on"]', "false"); await sleep(1500);
const options = await ev(`return document.querySelectorAll('#cpu-flag-names option').length`);
check("The flag field suggests the recognized flags", options === host, String(options));
const preview = await ev(`return document.querySelector('#command-preview')?.innerText || ''`);
check("The launch preview shows the flag and both NUMA nodes", /max,avx2=off/.test(preview) && /node,nodeid=0,cpus=0-1,memdev=numa-mem0/.test(preview) && /node,nodeid=1,cpus=2-3,memdev=numa-mem1/.test(preview) && /size=512M/.test(preview), (preview.match(/-cpu\s+\S+|-numa\s+\S+/g) || []).join(" "));
await shot("form-cpu");
await click('[data-action="wizard-create-start"]');
await waitFor(`!document.querySelector('#machine-form')`, 15000);
const id = await ev(`for (let i = 0; i < 100; i++) { const m = (await (await fetch('/api/state')).json()).machines.find((x) => x.name === ${JSON.stringify(machineName)}); if (m && m.state === 'running') return m.id; await new Promise((r) => setTimeout(r, 200)); } const m = (await (await fetch('/api/state')).json()).machines.find((x) => x.name === ${JSON.stringify(machineName)}); return m ? 'state ' + m.state + ' ' + (m.error || '') : 'no machine';`);
check("QEMU starts the machine with two NUMA nodes and the flag off", /^[a-f0-9-]{36}$/.test(id), id);
const saved = await ev(`const m=(await (await fetch('/api/state')).json()).machines.find((x)=>x.id==='${id}'); return JSON.stringify({numa:m?.numa, cpuFlags:m?.cpuFlags});`);
check("The machine record keeps the NUMA nodes and flag", saved === JSON.stringify({ numa: { nodes: 2 }, cpuFlags: [{ name: "avx2", on: false }] }), saved);
const memdev = await ev(`return JSON.stringify((await (await fetch('/api/machines/${id}/monitor/memdev')).json()).result.map((m)=>[m.id, m.size]).sort())`);
check("QEMU reports two 512 MiB memory backends", memdev === JSON.stringify([["numa-mem0", 536870912], ["numa-mem1", 536870912]]), memdev);
const nodes = await ev(`return JSON.stringify((await (await fetch('/api/machines/${id}/monitor/cpus')).json()).result.map((c)=>c.props['node-id']))`);
check("QEMU places two CPUs on each node", nodes === "[0,0,1,1]", nodes);
await ev(`const b=[...document.querySelectorAll('[data-action]')].find((x)=>x.dataset.action.includes('${id}') && /console|open/.test(x.dataset.action)); b?.click(); return 1;`);
await waitFor(`document.querySelector('[data-action="machine-tab:monitor"]')`);
await click('[data-action="machine-tab:monitor"]'); await sleep(500);
await click('[data-action="monitor-query:memdev"]');
await waitFor(`document.querySelector('.mon-out h2')?.innerText === 'Memory backends' && document.querySelector('.mon-result')`);
await shot("monitor-memdev");
await ev(`const s=await (await fetch('/api/session')).json(); await fetch('/api/machines/${id}/action',{method:'POST',headers:{'content-type':'application/json','x-csrf-token':s.csrf},body:JSON.stringify({action:'stop'})}); return 1;`);
writeFileSync(path.join(outDir, "cpu-numa.json"), JSON.stringify({ origin, at: new Date().toISOString(), results }, null, 2));
ws.close(); stopBrowser(edge);
process.exit(results.every((r) => r.ok) ? 0 : 1);
