// Returns the Cantonese text for a server message, or null when it is unknown
// (for example raw QEMU output, which stays exactly as QEMU printed it).
export function cantoneseServerError(message) {
  const text = String(message ?? "");
  if (Object.hasOwn(SERVER_ERRORS, text)) return SERVER_ERRORS[text];
  for (const p of SERVER_ERROR_PATTERNS) {
    const m = text.match(p.re);
    // A pattern's optional map translates a captured phrase as well.
    if (m) return p.yue.replace(/\$(\d)/g, (_, i) => p.map?.[m[Number(i)]] ?? m[Number(i)] ?? "");
  }
  return null;
}

// Formats a server message for the chosen language with the app's t(en, yue) helper.
export function localizeServerError(message, t) {
  const yue = cantoneseServerError(message);
  return yue ? t(String(message), yue) : String(message ?? "");
}
